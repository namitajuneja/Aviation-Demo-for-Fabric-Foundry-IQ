USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FABRIC_MIRROR_ROLE;
CREATE WAREHOUSE IF NOT EXISTS FABRIC_MIRROR_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Allows the connector to resume and use only the dedicated XS warehouse.
GRANT USAGE, OPERATE ON WAREHOUSE FABRIC_MIRROR_WH TO ROLE FABRIC_MIRROR_ROLE;
-- Allows discovery of the source database without ownership or write access.
GRANT USAGE ON DATABASE AVIATION_DEMO TO ROLE FABRIC_MIRROR_ROLE;
-- Allows discovery of the mirrored schema.
GRANT USAGE ON SCHEMA AVIATION_DEMO.OPS TO ROLE FABRIC_MIRROR_ROLE;
-- Allows initial snapshots and subsequent change-feed reads from source tables.
GRANT SELECT ON ALL TABLES IN SCHEMA AVIATION_DEMO.OPS TO ROLE FABRIC_MIRROR_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AVIATION_DEMO.OPS TO ROLE FABRIC_MIRROR_ROLE;

-- Run after setting FABRIC_MIRROR_USER in the session.
GRANT ROLE FABRIC_MIRROR_ROLE TO USER IDENTIFIER($FABRIC_MIRROR_USER);

