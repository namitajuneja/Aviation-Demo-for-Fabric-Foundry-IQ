USE SCHEMA AVIATION_DEMO.OPS;

CREATE STAGE IF NOT EXISTS AVIATION_PARQUET_STAGE
  URL = '&AVIATION_STAGE_URL'
  STORAGE_INTEGRATION = &AVIATION_STORAGE_INTEGRATION
  FILE_FORMAT = (TYPE = PARQUET);

CREATE OR REPLACE PROCEDURE LOAD_AVIATION_TABLE(TABLE_NAME VARCHAR, PATH_NAME VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
  EXECUTE IMMEDIATE 'TRUNCATE TABLE ' || IDENTIFIER(:TABLE_NAME);
  EXECUTE IMMEDIATE
    'COPY INTO ' || IDENTIFIER(:TABLE_NAME) ||
    ' FROM (SELECT $1:* FROM @AVIATION_PARQUET_STAGE/' || :PATH_NAME || ')' ||
    ' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE FORCE = TRUE';
  RETURN 'Loaded ' || TABLE_NAME;
END;
$$;

CALL LOAD_AVIATION_TABLE('AIRCRAFT', 'aircraft.parquet');
CALL LOAD_AVIATION_TABLE('ROUTE', 'route.parquet');
CALL LOAD_AVIATION_TABLE('FLIGHT', 'flight.parquet');
CALL LOAD_AVIATION_TABLE('BOOKING', 'booking/');
CALL LOAD_AVIATION_TABLE('CUSTOMER', 'customer.parquet');
CALL LOAD_AVIATION_TABLE('LOYALTY_TRANSACTION', 'loyalty_transaction.parquet');
CALL LOAD_AVIATION_TABLE('CARGO_SHIPMENT', 'cargo_shipment.parquet');
CALL LOAD_AVIATION_TABLE('MAINTENANCE_EVENT', 'maintenance_event.parquet');
CALL LOAD_AVIATION_TABLE('CREW_ROSTER', 'crew_roster.parquet');
CALL LOAD_AVIATION_TABLE('DISRUPTION_EVENT', 'disruption_event.parquet');

