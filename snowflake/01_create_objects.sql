CREATE DATABASE IF NOT EXISTS AVIATION_DEMO;
CREATE SCHEMA IF NOT EXISTS AVIATION_DEMO.OPS;
USE SCHEMA AVIATION_DEMO.OPS;

CREATE TABLE IF NOT EXISTS AIRCRAFT (
  TAIL_NUMBER VARCHAR NOT NULL, TYPE VARCHAR NOT NULL, OPCO VARCHAR NOT NULL,
  SEATS INTEGER NOT NULL, CARGO_CAPACITY_KG NUMBER(12,2) NOT NULL, DELIVERY_DATE DATE NOT NULL,
  CONSTRAINT PK_AIRCRAFT PRIMARY KEY (TAIL_NUMBER)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS ROUTE (
  ROUTE_ID VARCHAR NOT NULL, ORIGIN_IATA VARCHAR(3) NOT NULL, DEST_IATA VARCHAR(3) NOT NULL,
  DISTANCE_KM INTEGER NOT NULL, HAUL_TYPE VARCHAR NOT NULL,
  CONSTRAINT PK_ROUTE PRIMARY KEY (ROUTE_ID)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS FLIGHT (
  FLIGHT_NO VARCHAR NOT NULL, DATE DATE NOT NULL, TAIL_NUMBER VARCHAR NOT NULL, ROUTE_ID VARCHAR NOT NULL,
  OPCO VARCHAR NOT NULL, SCHEDULED_DEP TIMESTAMP_NTZ NOT NULL, ACTUAL_DEP TIMESTAMP_NTZ,
  DELAY_MINUTES INTEGER, DELAY_REASON_CODE VARCHAR, CANCELLED_FLAG BOOLEAN NOT NULL, LOAD_FACTOR NUMBER(6,4),
  CONSTRAINT PK_FLIGHT PRIMARY KEY (FLIGHT_NO, DATE)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS BOOKING (
  BOOKING_REF VARCHAR NOT NULL, FLIGHT_NO VARCHAR NOT NULL, DATE DATE NOT NULL, CUSTOMER_ID VARCHAR NOT NULL,
  FARE_CLASS VARCHAR NOT NULL, REVENUE_GBP NUMBER(14,2), ANCILLARY_GBP NUMBER(14,2), CHANNEL VARCHAR,
  CONSTRAINT PK_BOOKING PRIMARY KEY (BOOKING_REF)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS CUSTOMER (
  CUSTOMER_ID VARCHAR NOT NULL, HOME_AIRPORT VARCHAR(3), TIER VARCHAR, OPCO_AFFINITY VARCHAR, JOINED_DATE DATE,
  CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS LOYALTY_TRANSACTION (
  CUSTOMER_ID VARCHAR NOT NULL, POINTS_EARNED INTEGER, POINTS_REDEEMED INTEGER, PARTNER VARCHAR, DATE DATE
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS CARGO_SHIPMENT (
  AWB_NUMBER VARCHAR NOT NULL, FLIGHT_NO VARCHAR NOT NULL, DATE DATE NOT NULL, WEIGHT_KG NUMBER(14,2),
  CHARGEABLE_WEIGHT_KG NUMBER(14,2), LANE VARCHAR, YIELD_GBP_PER_KG NUMBER(12,3),
  COMMODITY VARCHAR, SHIPPER_ID VARCHAR, CONSTRAINT PK_CARGO PRIMARY KEY (AWB_NUMBER)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS MAINTENANCE_EVENT (
  TAIL_NUMBER VARCHAR NOT NULL, EVENT_DATE DATE NOT NULL, ATA_CHAPTER VARCHAR, PART_NUMBER VARCHAR,
  DOWNTIME_HOURS NUMBER(12,2), COST_GBP NUMBER(16,2), AOG_FLAG BOOLEAN
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS CREW_ROSTER (
  CREW_ID VARCHAR NOT NULL, OPCO VARCHAR, BASE VARCHAR(3), DUTY_DATE DATE, FLIGHT_NO VARCHAR,
  ROLE VARCHAR, DUTY_HOURS NUMBER(8,2), STANDBY_FLAG BOOLEAN
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS DISRUPTION_EVENT (
  FLIGHT_NO VARCHAR NOT NULL, DATE DATE NOT NULL, EVENT_TYPE VARCHAR, SEVERITY VARCHAR,
  PAX_AFFECTED INTEGER, REBOOK_COST_GBP NUMBER(16,2), COMPENSATION_GBP NUMBER(16,2)
) CHANGE_TRACKING = TRUE;

